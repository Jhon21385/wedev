function daysAgo(n: number) {
  const d = new Date()
  d.setDate(d.getDate() - n)
  return `${d.getFullYear()}-${`${d.getMonth() + 1}`.padStart(2, '0')}-${`${d.getDate()}`.padStart(2, '0')}`
}

/** Weighted 1–5 score. Effort is inverted; strategy carries the most weight. */
export function ideaScore(scores: Idea['scores']): number {
  const total = scores.audienceRelevance * 1.2 + scores.originality + (6 - scores.effort) + scores.potentialReach * 1.1 + scores.strategicRelevance * 1.3
  const max = 5 * 1.2 + 5 + 5 + 5 * 1.1 + 5 * 1.3
  return Math.round((total / max) * 100)
}
